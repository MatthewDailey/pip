"""Pip's launcher icon, generated from his art (apps/pip-app/app/src/main/assets/pip/pip.svg).

Writes into apps/pip-app/app/src/main/res:
  drawable/ic_launcher_foreground.xml   Pip, full colour, inside the adaptive icon's 66 dp safe zone
  drawable/ic_launcher_background.xml   the warm halo behind him
  drawable/ic_launcher_monochrome.xml   one-colour Pip for Android 13+ themed icons (alpha carries the face)
  drawable/ic_stat_pip.xml              the same silhouette, for notification small icons
  mipmap-<density>/ic_launcher.png      legacy square icon, every density
  mipmap-<density>/ic_launcher_round.png  legacy round icon, every density

Run it with `turbo run art:icon`; it needs the tools venv (cairosvg, pillow), which setup installs.
"""

import io
import re
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
ART = ROOT / "apps/pip-app/app/src/main/assets/pip/pip.svg"
RES = ROOT / "apps/pip-app/app/src/main/res"

# Adaptive icons are 108 dp; launchers mask them to at most the centre 72 dp and keep the centre 66 dp circle.
VIEW = 108
SCALE = 0.09  # Pip's 540 x 660 art becomes 48.6 x 59.4 dp, every corner inside the 66 dp circle
ART_W, ART_H = 540, 660
TX = (VIEW - ART_W * SCALE) / 2
TY = (VIEW - ART_H * SCALE) / 2 - 1  # a dp up: the hat's tip is lighter than the face's bulk

# Theme tokens from the re-skin ref: the halo behind Pip and a slightly deeper rim, so the peach face still reads.
HALO_IN = "#FFF6EF"
HALO_OUT = "#F6DCCD"

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def read_art():
    svg = ART.read_text()
    paths = dict(re.findall(r'<path id="(\w+)" fill="#\w+" d="([^"]+)"', svg))
    fills = dict(re.findall(r'<path id="(\w+)" fill="(#\w+)"', svg))
    eyes = re.findall(r'<ellipse id="(\w+)" cx="([\d.]+)" cy="([\d.]+)" rx="([\d.]+)" ry="([\d.]+)" fill="(#\w+)"', svg)
    return paths, fills, eyes


def ellipse_path(cx, cy, rx, ry):
    cx, cy, rx, ry = map(float, (cx, cy, rx, ry))
    return f"M {cx - rx} {cy} A {rx} {ry} 0 1 0 {cx + rx} {cy} A {rx} {ry} 0 1 0 {cx - rx} {cy} Z"


def vector(body: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/pip-art/icon/gen.py from Pip's art; run `turbo run art:icon` instead of editing. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{VIEW}dp"\n    android:height="{VIEW}dp"\n'
        f'    android:viewportWidth="{VIEW}"\n    android:viewportHeight="{VIEW}">\n{body}</vector>\n'
    )


def group(body: str) -> str:
    return (
        f'    <group android:translateX="{TX:.2f}" android:translateY="{TY:.2f}"'
        f' android:scaleX="{SCALE}" android:scaleY="{SCALE}">\n{body}    </group>\n'
    )


def path_xml(d: str, fill: str, alpha: float = 1.0) -> str:
    a = f' android:fillAlpha="{alpha}"' if alpha < 1 else ""
    return f'        <path android:fillColor="{fill}"{a} android:pathData="{d}" />\n'


def pip_svg(paths, fills, eyes, background: bool, clip: str | None) -> str:
    """Pip as plain SVG in the same 108-unit frame, for the legacy PNGs."""
    shapes = "".join(f'<path fill="{fills[k]}" d="{paths[k]}"/>' for k in ("hat", "face"))
    shapes += "".join(f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{f}"/>' for _, cx, cy, rx, ry, f in eyes)
    bg = (
        '<defs><radialGradient id="h" cx="50%" cy="45%" r="60%">'
        f'<stop offset="0" stop-color="{HALO_IN}"/><stop offset="1" stop-color="{HALO_OUT}"/></radialGradient></defs>'
        f'<rect width="{VIEW}" height="{VIEW}" fill="url(#h)"/>'
        if background
        else ""
    )
    body = f'{bg}<g transform="translate({TX:.2f} {TY:.2f}) scale({SCALE})">{shapes}</g>'
    clip_def = ""
    if clip:
        clip_def = f'<clipPath id="c">{clip}</clipPath>'
        body = f'<g clip-path="url(#c)">{body}</g>'
    # Legacy icons show the centre 72 of the 108 frame, like an adaptive icon under its mask.
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><defs>{clip_def}</defs>{body}</svg>'


def main():
    paths, fills, eyes = read_art()
    eye_paths = [(ellipse_path(cx, cy, rx, ry), f) for _, cx, cy, rx, ry, f in eyes]

    fg = path_xml(paths["hat"], fills["hat"]) + path_xml(paths["face"], fills["face"])
    fg += "".join(path_xml(d, f) for d, f in eye_paths)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(group(fg)))

    # Themed icons use only alpha: the hat is solid, the face a lighter tint, the eyes solid again.
    mono = path_xml(paths["hat"], "#FFFFFFFF") + path_xml(paths["face"], "#FFFFFFFF", 0.5)
    mono += "".join(path_xml(d, "#FFFFFFFF") for d, _ in eye_paths)
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(group(mono)))
    (RES / "drawable/ic_stat_pip.xml").write_text(vector(group(mono)).replace(
        f'android:width="{VIEW}dp"\n    android:height="{VIEW}dp"', 'android:width="24dp"\n    android:height="24dp"'))

    bg = (
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="radial" android:centerX="54" android:centerY="48" android:gradientRadius="64">\n'
        f'                <item android:offset="0" android:color="{HALO_IN}" />\n'
        f'                <item android:offset="1" android:color="{HALO_OUT}" />\n'
        "            </gradient>\n        </aapt:attr>\n    </path>\n"
    )
    (RES / "drawable/ic_launcher_background.xml").write_text(
        vector(bg).replace("<vector ", '<vector xmlns:aapt="http://schemas.android.com/aapt"\n    ', 1))

    square = '<rect x="18" y="18" width="72" height="72" rx="14"/>'
    circle = '<circle cx="54" cy="54" r="36"/>'
    for density, px in DENSITIES.items():
        out = RES / f"mipmap-{density}"
        out.mkdir(exist_ok=True)
        for old in out.glob("ic_launcher*.webp"):
            old.unlink()
        for name, clip in (("ic_launcher", square), ("ic_launcher_round", circle)):
            png = cairosvg.svg2png(bytestring=pip_svg(paths, fills, eyes, True, clip).encode(), output_width=px, output_height=px)
            Image.open(io.BytesIO(png)).save(out / f"{name}.png", optimize=True)
    print(f"icon: wrote drawables and {len(DENSITIES) * 2} legacy PNGs under {RES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
